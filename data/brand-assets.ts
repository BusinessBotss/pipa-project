/** Helper: returns the first hero_image asset for a brand with a safe non-empty URL, or null */
export function getBrandHeroAsset(brandId: string): BrandAsset | null {
  return (
    brandAssets.find(
      (a) => a.brandId === brandId && a.type === 'hero_image' && a.url !== '' && a.isPublic,
    ) ?? null
  );
}

/** Helper: returns all gallery_image assets for a brand with non-empty URLs */
export function getBrandGalleryAssets(brandId: string): BrandAsset[] {
  return brandAssets.filter(
    (a) => a.brandId === brandId && a.type === 'gallery_image' && a.url !== '' && a.isPublic,
  );
}
